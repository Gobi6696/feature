  // Core string getter
  static String translate(String key, String lang) {
    return _strings[lang]?[key] ?? key;
  }

  // Dam name translator
  static String translateDamName(
    String damId,
    String defaultName,
    String lang,
  ) {
    if (lang == 'ta') {
      return _names[damId]?['ta'] ?? defaultName;
    }
    return _names[damId]?['en'] ?? defaultName;
  }

  // District translator
  static String translateDistrict(String district, String lang) {
    if (lang == 'ta') {
      return _districtsTa[district] ?? district;
    }
    return district;
  }

  // River translator
  static String translateRiver(String river, String lang) {
    if (lang == 'ta') {
      return _riversTa[river] ?? river;
    }
    return river;
  }

  // Weather translator
  static String translateWeather(String weather, String lang) {
    if (lang == 'ta') {
      return _weatherTa[weather] ?? weather;
    }
    return weather;
  }

  // Sluice gate translator
  static String translateGates(String gates, String lang) {
    if (lang == 'ta') {
      // Find direct matches or partial translations
      for (var entry in _gatesTa.entries) {
        if (gates.trim() == entry.key.trim() || gates.contains(entry.key)) {
          return entry.value;
        }
      }
      return 'பாசன மதகு செயல்பாட்டில் உள்ளது';
    }
    return gates;
  }
